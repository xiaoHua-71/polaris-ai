package com.xiaohua.polaris.memory;

import java.util.List;
import java.util.UUID;

import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.ai.chat.messages.AssistantMessage;
import org.springframework.ai.chat.messages.Message;
import org.springframework.ai.chat.messages.MessageType;
import org.springframework.ai.chat.messages.SystemMessage;
import org.springframework.ai.chat.messages.UserMessage;
import org.springframework.jdbc.core.JdbcTemplate;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

class JdbcChatMemoryRepositoryTests {

    private JdbcChatMemoryRepository repository;

    @BeforeEach
    void setUp() {
        JdbcDataSource dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:chat-memory-" + UUID.randomUUID() + ";MODE=MySQL;DB_CLOSE_DELAY=-1");
        dataSource.setUser("sa");
        JdbcTemplate jdbcTemplate = new JdbcTemplate(dataSource);
        jdbcTemplate.execute("""
                CREATE TABLE chat_message (
                    id              BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    conversation_id VARCHAR(64) NOT NULL,
                    message_type    VARCHAR(16) NOT NULL,
                    content         CLOB        NOT NULL,
                    created_at      TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """);
        repository = new JdbcChatMemoryRepository(jdbcTemplate);
    }

    @Test
    void savesAndReadsMessagesInInsertionOrder() {
        repository.saveAll("c1", List.of(
                new UserMessage("我叫 Alice"),
                new AssistantMessage("你好，Alice")));

        List<Message> messages = repository.findByConversationId("c1");

        assertThat(messages).hasSize(2);
        assertThat(messages.getFirst().getMessageType()).isEqualTo(MessageType.USER);
        assertThat(messages.getFirst().getText()).isEqualTo("我叫 Alice");
        assertThat(messages.getLast().getMessageType()).isEqualTo(MessageType.ASSISTANT);
        assertThat(messages.getLast().getText()).isEqualTo("你好，Alice");
    }

    @Test
    void saveAllReplacesExistingMessages() {
        repository.saveAll("c1", List.of(new UserMessage("第一轮"), new AssistantMessage("第一次回答")));

        repository.saveAll("c1", List.of(new UserMessage("第二轮")));

        assertThat(repository.findByConversationId("c1"))
                .extracting(Message::getText)
                .containsExactly("第二轮");
    }

    @Test
    void findConversationIdsReturnsDistinctIds() {
        repository.saveAll("c1", List.of(new UserMessage("a")));
        repository.saveAll("c2", List.of(new UserMessage("b")));
        repository.saveAll("c2", List.of(new UserMessage("c")));

        assertThat(repository.findConversationIds()).containsExactlyInAnyOrder("c1", "c2");
    }

    @Test
    void deleteByConversationIdOnlyRemovesThatConversation() {
        repository.saveAll("c1", List.of(new UserMessage("a")));
        repository.saveAll("c2", List.of(new UserMessage("b")));

        repository.deleteByConversationId("c1");

        assertThat(repository.findByConversationId("c1")).isEmpty();
        assertThat(repository.findByConversationId("c2")).hasSize(1);
    }

    @Test
    void mapsSystemMessage() {
        repository.saveAll("c1", List.of(new SystemMessage("系统提示")));

        Message message = repository.findByConversationId("c1").getFirst();

        assertThat(message.getMessageType()).isEqualTo(MessageType.SYSTEM);
        assertThat(message.getText()).isEqualTo("系统提示");
    }

    @Test
    void rejectsToolMessagesUntilM5() {
        assertThatThrownBy(() -> JdbcChatMemoryRepository.toMessage("TOOL", "{}"))
                .isInstanceOf(IllegalStateException.class)
                .hasMessageContaining("M5");
    }
}
